import {build} from 'esbuild';
import {readFile} from 'node:fs/promises';

// Chrome injects this single packaged file afresh for every request. Keep the
// generated bundle checked in so installing the extension needs no build step.
await build({
  entryPoints:['src/conversation-dom.js'],
  outfile:'extension/conversation-dom.js',
  bundle:true,
  platform:'browser',
  format:'iife',
  target:'chrome116',
  legalComments:'inline',
  banner:{js:'// Generated by npm run build:reader. Edit src/conversation-dom.js instead.\n/*! Bundled Turndown and turndown-plugin-gfm. Both use this license:\n'+(await readFile('node_modules/turndown/LICENSE','utf8')).trim()+'\n*/'}
});
